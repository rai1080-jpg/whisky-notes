import type { DrinkStyleKey } from './model';

/**
 * おすすめ提案に使う銘柄リスト。
 *
 * 味・香りの数値は一般に言われている特徴をもとにした「目安」であり、
 * 公式な官能評価ではない。ロットや熟成、個人の感じ方で変わるため、
 * 画面上でもその旨を明示している。
 * 価格は変動が大きいので金額ではなく3段階の帯だけを持つ。
 */
export type CatalogLevel = 1 | 2 | 3;
/** 1=手頃 / 2=中価格帯 / 3=高価格帯 */
export type PriceBand = 1 | 2 | 3;

export interface CatalogItem {
  id: string;
  name: string;
  category: string;
  region: string;
  price: PriceBand;
  taste: { sweetness: CatalogLevel; smokiness: CatalogLevel; body: CatalogLevel };
  aroma: { fruity: CatalogLevel; spicy: CatalogLevel; oak: CatalogLevel };
  /** 向いているとされる飲み方 */
  styles: DrinkStyleKey[];
  note: string;
}

export const PRICE_BAND_LABELS: Record<PriceBand, string> = {
  1: '手頃',
  2: '中価格帯',
  3: '高価格帯',
};

const item = (
  id: string,
  name: string,
  category: string,
  region: string,
  price: PriceBand,
  [sweetness, smokiness, body]: [CatalogLevel, CatalogLevel, CatalogLevel],
  [fruity, spicy, oak]: [CatalogLevel, CatalogLevel, CatalogLevel],
  styles: DrinkStyleKey[],
  note: string,
): CatalogItem => ({
  id,
  name,
  category,
  region,
  price,
  taste: { sweetness, smokiness, body },
  aroma: { fruity, spicy, oak },
  styles,
  note,
});

